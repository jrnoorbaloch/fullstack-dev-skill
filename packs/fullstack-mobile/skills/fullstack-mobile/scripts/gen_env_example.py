#!/usr/bin/env python3
"""Scan source code for environment variables and write/update .env.example (never copies real values).

Usage: python gen_env_example.py [project-dir]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

PATTERNS = [
    re.compile(r"process\.env\.([A-Z][A-Z0-9_]+)"),
    re.compile(r"process\.env\[['\"]([A-Z][A-Z0-9_]+)['\"]\]"),
    re.compile(r"import\.meta\.env\.([A-Z][A-Z0-9_]+)"),
    re.compile(r"os\.environ(?:\.get)?\(\s*['\"]([A-Z][A-Z0-9_]+)['\"]"),
    re.compile(r"os\.environ\[['\"]([A-Z][A-Z0-9_]+)['\"]\]"),
    re.compile(r"os\.getenv\(\s*['\"]([A-Z][A-Z0-9_]+)['\"]"),
    re.compile(r"env\(\s*['\"]([A-Z][A-Z0-9_]+)['\"]"),           # Laravel
    re.compile(r"Deno\.env\.get\(\s*['\"]([A-Z][A-Z0-9_]+)['\"]"),
]
EXTS = {".js", ".jsx", ".ts", ".tsx", ".mjs", ".cjs", ".py", ".php", ".vue", ".svelte"}
SKIP = {"node_modules", ".next", ".git", "dist", "build", ".venv", "venv", "__pycache__", ".expo", "vendor"}
IGNORE = {"NODE_ENV", "PORT", "CI", "HOME", "PATH"}


def main() -> int:
    root = Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
    found: dict[str, set[str]] = {}
    for f in root.rglob("*"):
        if f.suffix not in EXTS or any(p in SKIP for p in f.parts) or not f.is_file():
            continue
        text = f.read_text(encoding="utf-8", errors="ignore")
        for pat in PATTERNS:
            for name in pat.findall(text):
                if name not in IGNORE:
                    found.setdefault(name, set()).add(f.relative_to(root).as_posix())

    out = root / ".env.example"
    existing = {}
    if out.exists():
        for line in out.read_text(encoding="utf-8").splitlines():
            if "=" in line and not line.lstrip().startswith("#"):
                k, v = line.split("=", 1)
                existing[k.strip()] = v
    lines = ["# Generated by gen_env_example.py — fill in real values in .env (never commit .env)"]
    for name in sorted(set(found) | set(existing)):
        where = ", ".join(sorted(found.get(name, [])))[:120]
        if where:
            lines.append(f"# used in: {where}")
        lines.append(f"{name}={existing.get(name, '')}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} with {len(set(found) | set(existing))} variables.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
